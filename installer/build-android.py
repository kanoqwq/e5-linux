#!/usr/bin/env python3
"""Build the Android host using existing SDK/NDK and the shared UI source.

Invoke through tools/build-release.py run. This builds no kernel or rootfs.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import runpy
import subprocess
import sys

HERE=Path(__file__).resolve().parent
MOBILE=HERE/'mobile'


def sources():
    files=[HERE/'build-android.py',HERE/'release-index.py']
    for root in (HERE/'backend',HERE/'ui/src',MOBILE):
        for p in root.rglob('*'):
            if p.is_file() and not any(part in {'.gradle','.kotlin','build','target','__pycache__','.idea','.tauri','schemas','node_modules','autogenerated','generated','jniLibs'} for part in p.relative_to(root).parts) and p.name not in {'local.properties','tauri.settings.gradle','tauri.build.gradle.kts','tauri.properties'} and 'gen/android/app/src/main/assets/' not in p.relative_to(root).as_posix():
                files.append(p)
    files += [HERE/'ui'/name for name in ('package.json','package-lock.json','vite.config.ts','index.html','diff.html','ota.html','release-index.html')]
    shared=runpy.run_path(str(HERE/'package_gui.py'))['sources']()
    return dict(shared,**{os.path.relpath(p,HERE).replace('\\','/'):hashlib.sha256(p.read_bytes().replace(b'\r\n',b'\n') if p.suffix in {'.py','.kt','.kts','.rs','.toml','.json','.ts','.tsx','.html','.css','.xml','.properties','.gradle'} else p.read_bytes()).hexdigest() for p in sorted(set(files))})


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--sdk',type=Path,required=True)
    parser.add_argument('--ndk',default='27.0.12077973')
    parser.add_argument('--jdk',type=Path,required=True)
    parser.add_argument('--build-python',type=Path,required=True,help='Python 3.13 on the build machine, matching embedded Python')
    parser.add_argument('--debug',action='store_true')
    parser.add_argument('--target',choices=('aarch64','x86_64'),default='aarch64')
    parser.add_argument('--signing-config',type=Path,help='Private local signing config, optionally with previous key and rotation lineage')
    parser.add_argument('--keystore',type=Path,help='Release signing key; passwords come from OPENWRT_ANDROID_STORE_PASSWORD and OPENWRT_ANDROID_KEY_PASSWORD')
    parser.add_argument('--key-alias',default='openwrt-tools')
    args=parser.parse_args()
    signing={};passwords={}
    if args.signing_config:
        if args.keystore:raise ValueError('Choose signing-config or keystore, not both')
        signing=json.loads(args.signing_config.read_text(encoding='utf-8'))
        args.keystore=Path(signing['keystore']);args.key_alias=signing.get('alias','openwrt-tools')
        passwords={'OPENWRT_ANDROID_STORE_PASSWORD':signing['password'],'OPENWRT_ANDROID_KEY_PASSWORD':signing.get('key_password',signing['password'])}
        if bool(signing.get('lineage'))!=bool(signing.get('previous')):raise ValueError('Signing rotation needs both lineage and the previous key')
        if signing.get('lineage'):
            for path in (signing['lineage'],signing['previous']['keystore']):
                if not Path(path).is_file():raise ValueError('Missing signing rotation input: '+str(path))
    if not args.debug or args.keystore:
        if not args.keystore or not args.keystore.is_file():raise ValueError('Release builds require a persistent Android signing key')
        if not all(passwords.get(k) or os.environ.get(k) for k in ('OPENWRT_ANDROID_STORE_PASSWORD','OPENWRT_ANDROID_KEY_PASSWORD')):
            raise ValueError('Android signing password environment is missing')
    for path in (args.sdk,args.sdk/'ndk'/args.ndk,args.jdk/'bin/java.exe',args.build_python):
        if not path.exists():raise ValueError('Missing registered Android build input: '+str(path))
    version=subprocess.check_output([str(args.build_python),'-c','import sys;print("%d.%d"%sys.version_info[:2])'],text=True).strip()
    if version!='3.13':raise ValueError('Android wheels require matching build Python 3.13')
    env=dict(os.environ,**passwords,ANDROID_HOME=str(args.sdk.resolve()),ANDROID_SDK_ROOT=str(args.sdk.resolve()),
             NDK_HOME=str((args.sdk/'ndk'/args.ndk).resolve()),JAVA_HOME=str(args.jdk.resolve()),
             OPENWRT_BUILD_PYTHON=str(args.build_python.resolve()),CARGO_TARGET_DIR=str(HERE/'ui/src-tauri/target'))
    node=shutil.which('node')
    if not node:raise ValueError('Node is missing')
    env['OPENWRT_BUILD_NODE']=node
    env['OPENWRT_TAURI_CLI']=str(HERE/'ui/node_modules/@tauri-apps/cli/tauri.js')
    env['PATH']=str(args.jdk/'bin')+os.pathsep+env['PATH']
    cli=HERE/'ui/node_modules/.bin/tauri.cmd'
    if not cli.is_file():raise ValueError('Install the existing UI lockfile dependencies first')
    dependency=json.loads((MOBILE/'vendor/adb-shell.json').read_text())
    wheel=MOBILE/'vendor'/dependency['wheel']
    if hashlib.sha256(wheel.read_bytes()).hexdigest()!=dependency['wheel_sha256']:
        raise ValueError('Embedded ADB dependency checksum differs')
    if not (MOBILE/'src-tauri/gen/android/gradlew.bat').is_file():raise ValueError('Android project is missing; restore tracked mobile sources')
    target_triple={'aarch64':'aarch64-linux-android','x86_64':'x86_64-linux-android'}[args.target]
    subprocess.run(['rustup','target','add',target_triple,'--toolchain','1.90.0'],env=env,check=True)
    if not (MOBILE/'src-tauri/Cargo.lock').exists():
        subprocess.run(['cargo','generate-lockfile','--manifest-path',str(MOBILE/'src-tauri/Cargo.toml')],cwd=MOBILE,env=env,check=True)
    before=sources()
    state=HERE/'out/build-state';state.mkdir(parents=True,exist_ok=True)
    (state/('android-source-'+args.target+'.json')).write_text(json.dumps(before,indent=2)+'\n')
    command=[str(cli),'android','build','--target',args.target,'--apk']
    if args.debug:command+=['--debug']
    subprocess.run(command,cwd=MOBILE,env=env,check=True)
    after=sources()
    if after!=before:
        changed=sorted(k for k in set(before)|set(after) if before.get(k)!=after.get(k))
        raise ValueError('Source changed during Android compilation; rebuild: '+', '.join(changed[:20]))
    apks=list((MOBILE/'src-tauri/gen/android/app/build/outputs/apk').rglob('*.apk'))
    apks=[p for p in apks if ('debug' in p.name)==args.debug]
    if len(apks)!=1:raise ValueError('Expected one ARM64 APK: '+repr(apks))
    from mobile.apk import validate
    validation=validate(apks[0],args.target)
    artifact=HERE/'artifacts/android';artifact.mkdir(parents=True,exist_ok=True)
    label='OpenWrt-Tools'+('-emulator' if args.target=='x86_64' else '')
    target=artifact/(label+('-debug.apk' if args.debug else '.apk'))
    if args.debug and not args.keystore:shutil.copy2(apks[0],target)
    else:
        versions=sorted((args.sdk/'build-tools').iterdir(),key=lambda p:tuple(int(v) for v in p.name.split('.') if v.isdigit()))
        signer=next((p/'apksigner.bat' for p in reversed(versions) if (p/'apksigner.bat').is_file()),None)
        if signer is None:raise ValueError('Android apksigner is missing from the selected SDK')
        signing_env=dict(env)
        command=[str(signer),'sign']
        if signing.get('lineage'):
            previous=signing['previous']
            signing_env['OPENWRT_ANDROID_PREVIOUS_STORE_PASSWORD']=previous['password']
            signing_env['OPENWRT_ANDROID_PREVIOUS_KEY_PASSWORD']=previous.get('key_password',previous['password'])
            command+=['--ks',str(previous['keystore']),'--ks-key-alias',previous.get('alias','openwrt-tools'),
                      '--ks-pass','env:OPENWRT_ANDROID_PREVIOUS_STORE_PASSWORD','--key-pass','env:OPENWRT_ANDROID_PREVIOUS_KEY_PASSWORD','--next-signer']
        command+=['--ks',str(args.keystore),'--ks-key-alias',args.key_alias,
                  '--ks-pass','env:OPENWRT_ANDROID_STORE_PASSWORD','--key-pass','env:OPENWRT_ANDROID_KEY_PASSWORD']
        if signing.get('lineage'):command+=['--lineage',str(signing['lineage']),'--rotation-min-sdk-version','28']
        subprocess.run(command+['--out',str(target),str(apks[0])],env=signing_env,check=True)
        subprocess.run([str(signer),'verify','--verbose',str(target)],env=env,check=True)
    (artifact/(label+('-debug' if args.debug else '')+'-build.json')).write_text(json.dumps({'protocol':1,'platform':'android-'+args.target,'debug':args.debug,'source':before,'validation':validation,'signing':{'alias':args.key_alias,'rotated':bool(signing.get('lineage'))},
        'files':{target.name:hashlib.sha256(target.read_bytes()).hexdigest()}},indent=2)+'\n')
    print(target)


if __name__=='__main__':main()
